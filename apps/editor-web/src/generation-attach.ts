import type { CommandTransaction } from '@joy-media/commands';
import type {
  BrowserAssetRegistration,
  BrowserControlPlaneClient,
} from './control-plane-client.js';
import type { EditorSession } from './editor-session.js';
import { buildMediaPlacementDocument, withImportedAsset } from './place-timeline-element.js';
import type { MediaPlacementAsset } from './place-timeline-element.js';
import { buildTimelineMediaImportTransaction } from './timeline-media-import.js';

/** A picture on the timeline has no source length, so it gets this many microseconds. */
export const GENERATED_PICTURE_DURATION_US = 5_000_000;

/** The part of a completed generation job record that attaching needs (see desktop GenerationJobRecord). */
export interface AttachableGenerationJob {
  readonly id: string;
  readonly kind: 'image' | 'video';
  readonly provider: string;
  readonly model: string;
  readonly prompt: string;
  readonly state: string;
  readonly sha256?: string | undefined;
  readonly createdAt: string;
}

/** The generated file as it sits on disk. Bytes and mime type come from the caller, not the job record. */
export interface AttachableGenerationFile {
  readonly displayName: string;
  readonly mimeType: string;
  readonly bytes: number;
  /** Required for video; pictures use GENERATED_PICTURE_DURATION_US. */
  readonly durationUs?: number;
  readonly width?: number;
  readonly height?: number;
}

export interface AttachGeneratedJobOptions {
  readonly projectId: string;
  readonly job: AttachableGenerationJob;
  readonly file: AttachableGenerationFile;
  readonly session: Pick<
    EditorSession,
    'timelineProject' | 'visualProject' | 'replaceVisualProject' | 'dispatchCompound'
  >;
  readonly client: Pick<BrowserControlPlaneClient, 'registerAsset'>;
  /** Place a clip on the first free visual track at the playhead. Registration alone when false. */
  readonly placeOnTimeline: boolean;
  readonly playheadUs: number;
  readonly lockedTrackIds?: ReadonlySet<string>;
}

export interface AttachGeneratedJobResult {
  readonly assetId: string;
  /** True only when this call registered the asset; a repeat attach of the same file does not. */
  readonly registeredAsset: boolean;
  readonly clipId?: string;
}

/** Content-addressed: the same generated bytes always map to the same asset id. */
export function generatedAssetIdForSha256(sha256: string): string {
  return `generated-${sha256}`;
}

/**
 * Attaches a completed generation job to the project.
 *
 * Order matters for undo: the asset (desktop catalog and project document) is
 * added first, outside the undo history, so one Undo removes only the clip.
 * The clip then goes in as one compound transaction on the first free visual
 * track at the playhead.
 */
export async function attachGeneratedJob(
  options: AttachGeneratedJobOptions,
): Promise<AttachGeneratedJobResult> {
  const { job, file, session } = options;
  if (job.state !== 'completed') throw new Error('The generation job has not finished.');
  if (job.sha256 === undefined || !/^[a-f0-9]{64}$/.test(job.sha256)) {
    throw new Error('The generated file has no valid checksum.');
  }
  if (!Number.isSafeInteger(file.bytes) || file.bytes <= 0) {
    throw new Error('The generated file is empty or its size is unknown.');
  }
  const mediaKind = job.kind === 'image' ? 'image' : 'video';
  if (!file.mimeType.startsWith(`${mediaKind}/`)) {
    throw new Error('The generated file type does not match the job kind.');
  }

  const assetId = generatedAssetIdForSha256(job.sha256);
  const durationUs = job.kind === 'image' ? GENERATED_PICTURE_DURATION_US : file.durationUs;
  if (
    options.placeOnTimeline &&
    (durationUs === undefined || !Number.isSafeInteger(durationUs) || durationUs <= 0)
  ) {
    throw new Error('The video duration is unknown, so the clip cannot be placed.');
  }

  const descriptor = {
    mimeType: file.mimeType,
    ...(file.width === undefined ? {} : { width: file.width }),
    ...(file.height === undefined ? {} : { height: file.height }),
    ...(job.kind === 'video' && durationUs !== undefined ? { durationUs } : {}),
  };
  const asset: MediaPlacementAsset = {
    id: assetId,
    kind: mediaKind,
    displayName: file.displayName,
    sha256: job.sha256,
    bytes: file.bytes,
    descriptor,
    generationProvenance: {
      providerId: job.provider,
      modelId: job.model,
      // The job record stores no separate model version, so none is invented.
      modelVersion: 'unrecorded',
      prompt: job.prompt,
      inputAssetHashes: [],
      parameters: { generationJobId: job.id, kind: job.kind },
      generatedAssetId: assetId,
      createdAt: job.createdAt,
    },
  };

  // Planning is pure: nothing is registered or dispatched until the clip is known to fit.
  const root = session.timelineProject.compositions[session.timelineProject.rootCompositionId];
  if (root === undefined) throw new Error('The main timeline is unavailable.');
  let plan: TimelinePlan | undefined;
  if (options.placeOnTimeline) {
    const label = `Place generated ${file.displayName}`;
    const transaction = buildTimelineMediaImportTransaction(
      root,
      [
        {
          id: assetId,
          kind: mediaKind,
          displayName: file.displayName,
          descriptor: {
            mimeType: file.mimeType,
            ...(durationUs === undefined ? {} : { durationUs }),
          },
        },
      ],
      options.playheadUs,
      options.lockedTrackIds ?? new Set(),
      () => `clip-gen-${job.id}`,
      { mode: 'first-free', startUs: options.playheadUs },
    );
    const insert = transaction.commands.find((command) => command.type === 'timeline.insertClip');
    if (insert?.type !== 'timeline.insertClip') throw new Error('The clip could not be placed.');
    plan = {
      label,
      commands: transaction.commands,
      trackId: insert.payload.trackId,
      clip: insert.payload.clip,
    };
  }

  let registeredAsset = false;
  if (session.visualProject.assets[assetId] === undefined) {
    const registration: BrowserAssetRegistration = {
      id: assetId,
      kind: mediaKind,
      displayName: file.displayName,
      sha256: job.sha256,
      bytes: file.bytes,
      descriptor,
      locations: [],
      // Generated files live in the app's own folder, not in the owner's asset library.
      internal: true,
    };
    await options.client.registerAsset(options.projectId, registration);
    registeredAsset = true;
    session.replaceVisualProject(withImportedAsset(session.visualProject, asset));
  }

  if (plan === undefined) return { assetId, registeredAsset };

  const document = buildMediaPlacementDocument({
    baseProject: session.visualProject,
    asset,
    clipId: plan.clip.id,
    planned: { compositionId: root.id, trackId: plan.trackId, clip: plan.clip },
  });
  session.dispatchCompound(plan.label, {
    document,
    timeline: { label: plan.label, commands: plan.commands },
  });
  return { assetId, registeredAsset, clipId: plan.clip.id };
}

interface TimelinePlan {
  readonly label: string;
  readonly commands: CommandTransaction['commands'];
  readonly trackId: string;
  readonly clip: InsertedClip;
}

type InsertedClip = Extract<
  CommandTransaction['commands'][number],
  { readonly type: 'timeline.insertClip' }
>['payload']['clip'];
