import type { AudioState, CommandTransaction } from '@joy-media/commands';
import type { BrowserControlPlaneClient } from './control-plane-client.js';
import type { EditorSession } from './editor-session.js';
import {
  describeMedia,
  importMediaFile,
  normalizedMimeType,
  type MediaImportOptions,
} from './media-import.js';
import { projectWithImportedAsset } from './media-project.js';
import { buildTimelineMediaImportTransaction } from './timeline-media-import.js';
import {
  applyTimelineMediaPlacement,
  type TimelineMediaPlacement,
} from './timeline-media-placement.js';

/** A picture on the timeline has no source length, so it gets this many microseconds. */
export const GENERATED_PICTURE_DURATION_US = 5_000_000;

/** The part of a completed generation job record that attaching needs (see desktop GenerationJobRecord). */
export interface AttachableGenerationJob {
  readonly id: string;
  readonly kind: 'image' | 'video';
  readonly provider: string;
  readonly model: string;
  readonly prompt: string;
  readonly state: string;
  readonly sha256?: string | undefined;
  readonly createdAt: string;
}

export interface AttachGeneratedJobOptions {
  readonly projectId: string;
  readonly projectTitle: string;
  readonly job: AttachableGenerationJob;
  /**
   * The generated bytes, read by the caller from the completed job output.
   * Its name becomes the library display name. Pass a file only after the
   * download has finished: the bytes are hashed and checked against job.sha256.
   */
  readonly file: File;
  readonly session: EditorSession;
  /** The audio state the placement writes into the document; the result returns the next one. */
  readonly audioState: AudioState;
  readonly client: Pick<
    BrowserControlPlaneClient,
    'ensureProject' | 'registerAsset' | 'assets' | 'uploadAssetOriginal'
  >;
  readonly originalAssetCache?: MediaImportOptions['originalAssetCache'];
  /** Overrides metadata reading; the default reads dimensions and duration from the file. */
  readonly describeMedia?: NonNullable<MediaImportOptions['describeMedia']>;
  /** Place a clip on the first free visual track at the playhead. Library and project record only when false. */
  readonly placeOnTimeline: boolean;
  readonly playheadUs: number;
  readonly lockedTrackIds?: ReadonlySet<string>;
}

export interface AttachGeneratedJobResult {
  readonly assetId: string;
  /** True when this call stored the file in the library; attaching a file already in the project does not. */
  readonly registeredAsset: boolean;
  readonly clipId?: string;
  readonly audioState: AudioState;
}

/** Content-addressed: the same generated bytes always map to the same asset id. */
export function generatedAssetIdForSha256(sha256: string): string {
  return `generated-${sha256}`;
}

/**
 * Attaches a completed generation job to the project.
 *
 * The bytes go into the local media library through importMediaFile, the same
 * route as a normal import: local cache, registration (a fresh session that
 * finds the asset already registered resumes it), then the original upload.
 * The library therefore holds the file before the project refers to it, and
 * the asset is not internal, so it survives a restart and stays visible.
 *
 * Refusals happen before anything is stored: unfinished job, bad checksum,
 * empty file, a type that does not match the job kind, a checksum mismatch
 * on the bytes, and a video whose duration is unknown (even when no clip is
 * placed, because the file would then be attached with no usable length).
 *
 * Undo: with placeOnTimeline, the asset record and the clip go in one
 * compound history entry, as applyTimelineMediaPlacement does for imports. One
 * Undo removes both from the project; the library copy stays, so Redo restores
 * them. Without a clip the asset record is its own single entry (replaceVisualProject).
 */
export async function attachGeneratedJob(
  options: AttachGeneratedJobOptions,
): Promise<AttachGeneratedJobResult> {
  const { job, file, session } = options;
  if (job.state !== 'completed') throw new Error('The generation job has not finished.');
  if (job.sha256 === undefined || !/^[a-f0-9]{64}$/.test(job.sha256)) {
    throw new Error('The generated file has no valid checksum.');
  }
  const sha256 = job.sha256;
  if (!Number.isSafeInteger(file.size) || file.size <= 0) {
    throw new Error('The generated file is empty or its size is unknown.');
  }
  const mediaKind = job.kind;
  const mimeType = normalizedMimeType(file);
  if (!mimeType.startsWith(`${mediaKind}/`)) {
    throw new Error('The generated file type does not match the job kind.');
  }
  if ((await sha256Hex(file)) !== sha256) {
    throw new Error('The generated file does not match its checksum.');
  }

  const descriptor = await (options.describeMedia ?? describeMedia)(file, mediaKind, mimeType);
  const durationUs = mediaKind === 'image' ? GENERATED_PICTURE_DURATION_US : descriptor.durationUs;
  if (mediaKind === 'video' && !isPositiveSafeInteger(durationUs)) {
    throw new Error('The video duration is unknown, so the generated clip cannot be attached.');
  }

  const assetId = generatedAssetIdForSha256(sha256);
  const asset: TimelineMediaPlacement['asset'] = {
    id: assetId,
    kind: mediaKind,
    displayName: file.name,
    sha256,
    bytes: file.size,
    descriptor: { ...descriptor, mimeType },
    generationProvenance: {
      providerId: job.provider,
      modelId: job.model,
      // The job record stores no separate model version, so none is invented.
      modelVersion: 'unrecorded',
      prompt: job.prompt,
      inputAssetHashes: [],
      parameters: { generationJobId: job.id, kind: job.kind },
      generatedAssetId: assetId,
      createdAt: job.createdAt,
    },
  };

  // Store the bytes first (outside the undo history). A project that already
  // holds this asset is not re-uploaded.
  const alreadyInProject = session.visualProject.assets[assetId] !== undefined;
  if (!alreadyInProject) {
    const imported = await importMediaFile({
      projectId: options.projectId,
      projectTitle: options.projectTitle,
      file,
      assetId,
      client: options.client,
      // The duration and size were checked above; reuse them instead of reading the file again.
      describeMedia: async () => descriptor,
      ...(options.originalAssetCache === undefined
        ? {}
        : { originalAssetCache: options.originalAssetCache }),
    });
    if (imported.sha256 !== sha256 || imported.bytes !== file.size) {
      throw new Error('The local media library did not keep the generated file unchanged.');
    }
  }

  // Plan after the upload: the timeline may have changed while the bytes were stored.
  const root = session.timelineProject.compositions[session.timelineProject.rootCompositionId];
  if (root === undefined) throw new Error('The main timeline is unavailable.');
  if (!options.placeOnTimeline) {
    if (!alreadyInProject) {
      session.replaceVisualProject(projectWithImportedAsset(session.visualProject, asset));
    }
    return { assetId, registeredAsset: !alreadyInProject, audioState: options.audioState };
  }

  const label = `Place generated ${file.name}`;
  const planned = buildTimelineMediaImportTransaction(
    root,
    [
      {
        id: assetId,
        kind: mediaKind,
        displayName: file.name,
        descriptor: {
          mimeType,
          ...(durationUs === undefined ? {} : { durationUs }),
        },
      },
    ],
    options.playheadUs,
    options.lockedTrackIds ?? new Set(),
    () => `clip-gen-${job.id}`,
    { mode: 'first-free', startUs: options.playheadUs },
  );
  const insert = planned.commands.find((command) => command.type === 'timeline.insertClip');
  if (insert?.type !== 'timeline.insertClip') throw new Error('The clip could not be placed.');
  const transaction: CommandTransaction = { label, commands: planned.commands };
  const audioState = applyTimelineMediaPlacement(session, options.audioState, transaction, [
    {
      asset,
      clipId: insert.payload.clip.id,
      // New media is fitted to the frame of the composition it lands in (T-D01).
      frame: { width: root.width, height: root.height },
    },
  ]);
  return {
    assetId,
    registeredAsset: !alreadyInProject,
    clipId: insert.payload.clip.id,
    audioState,
  };
}

function isPositiveSafeInteger(value: number | undefined): value is number {
  return value !== undefined && Number.isSafeInteger(value) && value > 0;
}

async function sha256Hex(blob: Blob): Promise<string> {
  const digest = await crypto.subtle.digest('SHA-256', await blob.arrayBuffer());
  return Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, '0')).join('');
}
